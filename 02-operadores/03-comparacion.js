let a = 10;

// Operadores deRelacionales
console.log(a > 5); // si es mayor
console.log(a >= 5); // si es mayor o igual
console.log(a < 5); // si es menor
console.log(a <= 5); // si es menor o igual

// Operadores de Igualdad
console.log(a == 10); // si a es igual a 10
console.log(a != 10); // si a es diferente a 10
console.log(a == "10"); // con == pregunta si el valor es igual y no el tipo de dato
console.log(a === 10); // preguntar si es igual el valor y tipo de dato
console.log(a !== 10); // preguntar si es diferente el valor y el tipo de dato